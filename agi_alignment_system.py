# ============================================================================
# HELPER FUNCTIONS
# ============================================================================

def _get_utc_timestamp() -> str:
    """Generate a high-precision ISO 8601 UTC timestamp."""
    return datetime.now(timezone.utc).isoformat()


# ============================================================================
# CORE DATA MODELS
# ============================================================================

@dataclass(frozen=True, slots=True)
class EvidenceEntry:
    """Represents a single piece of curated empirical or theoretical evidence."""

    source: str
    content: str
    url: str | None = None
    timestamp: str = field(default_factory=_get_utc_timestamp)


@dataclass(frozen=True, slots=True)
class PersonaAnalysis:
    """Structured output generated by a specific evaluation persona."""

    persona_name: str
    search_queries: tuple[str, ...]
    evidence_entries: tuple[EvidenceEntry, ...]
    analysis: str
    confidence: float
    key_findings: tuple[str, ...]
    warnings: tuple[str, ...]
    tradeoffs: tuple[str, ...]
    timestamp: str = field(default_factory=_get_utc_timestamp)


@dataclass(frozen=True, slots=True)
class SynthesisOutput:
    """Integrated multi-persona alignment evaluation and decision matrix."""

    query: str
    persona_results: dict[str, PersonaAnalysis]
    tradeoff_map: dict[str, tuple[str, ...]]
    user_alignment_factors: tuple[str, ...]
    decision_framework: str
    timestamp: str = field(default_factory=_get_utc_timestamp)


