class EvidenceStore:
    """Persistent storage for persona evaluation artifacts."""

    __slots__ = ("repo_path", "personas")

    DEFAULT_PERSONAS: Final[tuple[str, ...]] = (
        "Mechanist",
        "Empiricist",
        "Alignment_Auditor",
        "Adversary",
        "Capability_Analyst",
        "Values_Mapper",
        "Scalability_Killer",
        "Constraint_Validator",
        "Stakeholder_Impact",
        "Trajectory_Predictor",
        "Transparency_Auditor",
        "Long_Term_Impact",
    )

    def __init__(self, repo_path: str | Path = "./agi_evidence_repo") -> None:
        self.repo_path: Path = Path(repo_path).resolve()
        self.personas: dict[str, Any] = {}
        self._init_repo()

    def _init_repo(self) -> None:
        """Initialize directory hierarchy for target evaluation personas."""
        try:
            self.repo_path.mkdir(parents=True, exist_ok=True)
            for persona in self.DEFAULT_PERSONAS:
                (self.repo_path / persona).mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            logger.error("Failed to initialize evidence repository at %s: %s", self.repo_path, exc)
            raise

    def save_evidence(self, persona_name: str, analysis: PersonaAnalysis) -> str:
        """Atomically persist persona analysis artifacts to disk as formatted JSON."""
        persona_dir = self.repo_path / persona_name
        try:
            persona_dir.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            logger.error("Failed to create persona directory %s: %s", persona_dir, exc)
            raise

        safe_timestamp = analysis.timestamp.replace(":", "-")
        filename = f"{persona_name}_analysis_{safe_timestamp}.json"
        filepath = persona_dir / filename
        temp_filepath = persona_dir / f".{filename}.tmp"

        payload: dict[str, Any] = {
            "persona": persona_name,
            "timestamp": analysis.timestamp,
            "search_queries": list(analysis.search_queries),
            "evidence_count": len(analysis.evidence_entries),
            "evidence_sources": [entry.source for entry in analysis.evidence_entries],
            "analysis": analysis.analysis,
            "confidence": analysis.confidence,
            "key_findings": list(analysis.key_findings),
            "warnings": list(analysis.warnings),
            "tradeoffs": list(analysis.tradeoffs),
        }

        try:
            with temp_filepath.open("w", encoding="utf-8") as file_handle:
                json.dump(payload, file_handle, indent=2, ensure_ascii=False)
            temp_filepath.replace(filepath)
        except OSError as exc:
            logger.error("Failed to write evidence analysis for %s to %s: %s", persona_name, filepath, exc)
            if temp_filepath.exists():
                try:
                    temp_filepath.unlink(missing_ok=True)
                except OSError:
                    pass
            raise

        return str(filepath)

    def load_evidence(self, persona_name: str) -> PersonaAnalysis | None:
        """Retrieve the most recent analysis artifact for a specific persona."""
        persona_dir = self.repo_path / persona_name
        if not persona_dir.is_dir():
            return None

        try:
            json_files = sorted(
                path for path in persona_dir.iterdir()
                if path.is_file() and path.suffix == ".json"
            )
            if not json_files:
                return None

            latest_file = json_files[-1]
            with latest_file.open("r", encoding="utf-8") as file_handle:
                data = json.load(file_handle)

            if not isinstance(data, dict):
                logger.warning("Invalid data format in evidence file: %s", latest_file)
                return None

            return PersonaAnalysis(
                persona_name=str(data.get("persona", persona_name)),
                search_queries=tuple(str(q) for q in data.get("search_queries", [])),
                evidence_entries=(),
                analysis=str(data.get("analysis", "")),
                confidence=float(data.get("confidence", 0.0)),
                key_findings=tuple(str(f) for f in data.get("key_findings", [])),
                warnings=tuple(str(w) for w in data.get("warnings", [])),
                tradeoffs=tuple(str(t) for t in data.get("tradeoffs", [])),
                timestamp=str(data.get("timestamp", _get_utc_timestamp())),
            )
        except (OSError, json.JSONDecodeError, ValueError) as exc:
            logger.warning("Error loading evidence for persona %s: %s", persona_name, exc)
            return None


